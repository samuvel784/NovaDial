    testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
  }

  val uploadKeystorePath = System.getenv("KEYSTORE_PATH") ?: "$rootDir/my-upload-key.jks"
  val hasUploadKeystore = file(uploadKeystorePath).exists()

  signingConfigs {
    if (hasUploadKeystore) {
      create("release") {
        storeFile = file(uploadKeystorePath)
        storePassword = System.getenv("STORE_PASSWORD") ?: "android"
        keyAlias = System.getenv("KEY_ALIAS") ?: "upload"
        keyPassword = System.getenv("KEY_PASSWORD") ?: "android"
      }
    }
    val debugKeystore = file("${rootDir}/debug.keystore")
    if (debugKeystore.exists()) {
      create("debugConfig") {
        storeFile = debugKeystore
        storePassword = "android"
        keyAlias = "androiddebugkey"
        keyPassword = "android"
      }
    }
  }

  buildTypes {
    release {
      isCrunchPngs = false
      isMinifyEnabled = true
      isShrinkResources = true
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      // Without a real keystore the release APK is signed with the debug key, so it still INSTALLS for testing.
      // An unsigned APK shows "problem parsing the package". Google Play rejects debug-signed files:
      // set KEYSTORE_PATH / STORE_PASSWORD / KEY_ALIAS / KEY_PASSWORD (or my-upload-key.jks) before building the AAB you upload.
      signingConfig = if (hasUploadKeystore) signingConfigs.getByName("release") else signingConfigs.getByName("debug")
    }
    debug {
      signingConfig = signingConfigs.findByName("debugConfig") ?: signingConfigs.getByName("debug")
    }
  }
